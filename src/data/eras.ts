export function getEraById(id: string): Era | undefined {
  return ERAS.find(e => e.id === id);
}

export function getAdjacentEras(id: string): { prev: Era | null; next: Era | null } {
  const index = ERAS.findIndex(e => e.id === id);
  return {
    prev: index > 0 ? ERAS[index - 1] : null,
    next: index < ERAS.length - 1 ? ERAS[index + 1] : null,
  };
}
